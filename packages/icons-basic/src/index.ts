export const basicIcons: IconPack = {
  provider: 'basic',
  icons: Object.fromEntries(
    Object.entries(pictograms).map(([name, content]) => [
      `basic-${name}`,
      {
        viewBox: '0 0 24 24',
        monochrome: true,
        content: `<g fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">${content}</g>`,
      },
    ]),
  ),
  aliases: Object.fromEntries(
    Object.entries(synonyms).map(([alias, name]) => [
      /^[a-z]/.test(alias) ? `basic-${alias}` : alias,
      `basic-${name}`,
    ]),
  ),
  keywords: Object.fromEntries(
    Object.entries(basicCategories).flatMap(([category, names]) =>
      names.map((name) => [
        `basic-${name}`,
        [
          ...categoryWords[category as keyof typeof basicCategories],
          ...(roleWords[name] ?? []),
          ...Object.entries(synonyms)
            .filter(([, target]) => target === name)
            .map(([word]) => word),
        ],
      ]),
    ),
  ),
}

export default basicIcons
